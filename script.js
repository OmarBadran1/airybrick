// Form handling
const contactForm = document.getElementById('contactForm');
const formData = {
  name: '',
  email: '',
  phone: '',
  company: '',
  message: '',
  brickType: ''
};

function showSuccessMessage() {
  const successMessage = document.getElementById('successMessage');
  successMessage.classList.remove('hidden');
  setTimeout(() => {
    successMessage.classList.add('hidden');
  }, 3000);
}

function resetForm() {
  const inputs = contactForm.querySelectorAll('input, textarea, select');
  inputs.forEach(input => {
    input.value = '';
  });
}

if (contactForm) {
  contactForm.addEventListener('submit', (e) => {
    e.preventDefault();
    
    // Get form data
    const formElements = contactForm.elements;
    formData.name = formElements.name.value;
    formData.email = formElements.email.value;
    formData.phone = formElements.phone.value;
    formData.company = formElements.company.value;
    formData.message = formElements.message.value;
    formData.brickType = formElements.brickType.value;
    
    // In a real application, you would send this data to a server
    console.log('Form submitted:', formData);
    
    // Show success message and reset form
    showSuccessMessage();
    resetForm();
  });
}

// Smooth scrolling for navigation links
document.addEventListener('click', (e) => {
  if (e.target.matches('[data-scroll]')) {
    e.preventDefault();
    const targetId = e.target.getAttribute('href').slice(1);
    const targetElement = document.getElementById(targetId);
    
    if (targetElement) {
      targetElement.scrollIntoView({
        behavior: 'smooth'
      });
    }
  }
});

